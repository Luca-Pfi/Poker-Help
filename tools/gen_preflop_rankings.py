"""Generate poker_bot/preflop_data.py: a strength ordering of the 169 starting hands.

Each hand class is simulated against 1 and against 3 random opponents.
The final ranking blends both (heads-up equity alone overrates offsuit
big-card hands) plus a small playability bonus for suited / connected hands and small
pairs (set value).

Usage:  python tools/gen_preflop_rankings.py [iterations]
"""

import os
import random
import sys
from multiprocessing import Pool

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from poker_bot.cards import ALL_CLASSES, combos_for_class  # noqa: E402
from poker_bot.evaluator import RK, SK, FM, SUIT_START, score_keys  # noqa: E402


def equity_vs_random(args):
    label, n_opp, iters, seed = args
    rng = random.Random(seed)
    c1, c2 = combos_for_class(label)[0]
    deck = [c for c in range(52) if c != c1 and c != c2]
    need = 5 + 2 * n_opp
    total = 0.0
    for _ in range(iters):
        draw = rng.sample(deck, need)
        board = draw[:5]
        bk = sum(RK[c] for c in board)
        bs = SUIT_START + sum(SK[c] for c in board)
        bf = 0
        for c in board:
            bf |= FM[c]
        hero = score_keys(bk + RK[c1] + RK[c2], bs + SK[c1] + SK[c2], bf | FM[c1] | FM[c2])
        best = 0
        ties = 0
        for i in range(n_opp):
            a, b = draw[5 + 2 * i], draw[6 + 2 * i]
            v = score_keys(bk + RK[a] + RK[b], bs + SK[a] + SK[b], bf | FM[a] | FM[b])
            if v > best:
                best, ties = v, 1
            elif v == best:
                ties += 1
        if hero > best:
            total += 1.0
        elif hero == best:
            total += 1.0 / (ties + 1)
    return label, n_opp, total / iters


def main():
    iters = int(sys.argv[1]) if len(sys.argv) > 1 else 40000
    jobs = []
    for i, label in enumerate(ALL_CLASSES):
        jobs.append((label, 1, iters, 1000 + i))
        jobs.append((label, 3, iters, 5000 + i))
    with Pool() as pool:
        results = pool.map(equity_vs_random, jobs, chunksize=4)
    eq = {}
    for label, n, e in results:
        eq.setdefault(label, {})[n] = e

    def zscores(key):
        vals = [eq[l][key] for l in ALL_CLASSES]
        m = sum(vals) / len(vals)
        sd = (sum((v - m) ** 2 for v in vals) / len(vals)) ** 0.5
        return {l: (eq[l][key] - m) / sd for l in ALL_CLASSES}

    z1, z3 = zscores(1), zscores(3)

    def playability(label):
        # Raw equity ignores how well a hand plays post-flop (making strong
        # draws / disguised hands).  Real players' ranges reflect this.
        ranks = "23456789TJQKA"
        if len(label) == 2:
            # small pairs flop sets ~12% of the time and are played for that
            return max(0.0, 0.36 - 0.06 * ranks.index(label[0]))
        gap = ranks.index(label[0]) - ranks.index(label[1]) - 1
        bonus = 0.25 if label[2] == "s" else 0.0
        if gap == 0:
            bonus += 0.15
        elif gap == 1:
            bonus += 0.07
        return bonus

    score = {l: 0.45 * z1[l] + 0.55 * z3[l] + playability(l) for l in ALL_CLASSES}
    order = sorted(ALL_CLASSES, key=lambda l: -score[l])

    out = os.path.join(os.path.dirname(__file__), "..", "poker_bot", "preflop_data.py")
    with open(out, "w") as f:
        f.write('"""Generated by tools/gen_preflop_rankings.py (%d iterations per hand). Do not edit."""\n\n' % iters)
        f.write("# 169 starting hands from strongest to weakest\n")
        f.write("HAND_ORDER = [\n")
        for i in range(0, len(order), 12):
            f.write("    " + ", ".join('"%s"' % l for l in order[i:i + 12]) + ",\n")
        f.write("]\n\n")
        f.write("# Equity vs 1 and vs 3 random hands\n")
        f.write("EQUITY_VS_RANDOM = {\n")
        for l in order:
            f.write('    "%s": (%.4f, %.4f),\n' % (l, eq[l][1], eq[l][3]))
        f.write("}\n")
    print("wrote", out)
    print(" ".join(order[:40]))


if __name__ == "__main__":
    main()
